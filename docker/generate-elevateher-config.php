<?php
/**
 * Generates elevateher/config/config.php from Docker environment variables.
 * Called by entrypoint.sh on first container start.
 */

$configPath = '/var/www/public_html/elevateher/config/config.php';
if (file_exists($configPath)) {
    exit(0);
}

$dbHost = getenv('CHILD_DB_HOST') ?: 'db';
$dbName = getenv('CHILD_DB_NAME') ?: 'elevateher_main';
$dbUser = getenv('CHILD_DB_USER') ?: getenv('DB_USER') ?: 'root';
$dbPass = getenv('CHILD_DB_PASS') ?: getenv('DB_PASSWORD') ?: '';

$shard1Host = getenv('CHILD_DB_HOST_SHARD')  ?: $dbHost;
$shard1Name = getenv('CHILD_DB_NAME_SHARD')  ?: 'elevateher_shard_1';
$shard2Host = getenv('CHILD_DB_HOST_SHARD2') ?: $dbHost;
$shard2Name = getenv('CHILD_DB_NAME_SHARD2') ?: 'elevateher_shard_2';

$aiKey   = getenv('ELEVATEHER_AI_API_KEY') ?: getenv('ANTHROPIC_API_KEY') ?: '';
$aiModel = getenv('ELEVATEHER_AI_MODEL')   ?: 'claude-sonnet-4-6';
$fwSource = getenv('ELEVATEHER_FRAMEWORK_SOURCE') ?: 'local';
$fwPath   = getenv('ELEVATEHER_FRAMEWORK_PATH')   ?: '/var/www/public_html/dswa-framework/framework';
$appUrl   = getenv('ELEVATEHER_APP_URL')           ?: '';

$config = "<?php\n";
$config .= "// Auto-generated by Docker entrypoint on " . date('Y-m-d H:i:s') . "\n\n";

$config .= "// ─── Child App Main Database ────────────────────────────────────────────────\n";
$config .= "\$child_db_host = " . var_export($dbHost, true) . ";\n";
$config .= "\$child_db_name = " . var_export($dbName, true) . ";\n";
$config .= "\$child_db_user = " . var_export($dbUser, true) . ";\n";
$config .= "\$child_db_pass = " . var_export($dbPass, true) . ";\n\n";

$config .= "// ─── Child App Shard Databases ──────────────────────────────────────────────\n";
$config .= "\$childShardConfigs = [\n";
$config .= "    'shard1' => [\n";
$config .= "        'host' => " . var_export($shard1Host, true) . ",\n";
$config .= "        'name' => " . var_export($shard1Name, true) . ",\n";
$config .= "        'user' => " . var_export($dbUser, true) . ",\n";
$config .= "        'pass' => " . var_export($dbPass, true) . ",\n";
$config .= "    ],\n";
$config .= "    'shard2' => [\n";
$config .= "        'host' => " . var_export($shard2Host, true) . ",\n";
$config .= "        'name' => " . var_export($shard2Name, true) . ",\n";
$config .= "        'user' => " . var_export($dbUser, true) . ",\n";
$config .= "        'pass' => " . var_export($dbPass, true) . ",\n";
$config .= "    ],\n";
$config .= "];\n\n";

$config .= "// ─── AI Configuration ───────────────────────────────────────────────────────\n";
$config .= "\$ai_config = [\n";
$config .= "    'provider'    => 'anthropic',\n";
$config .= "    'model'       => " . var_export($aiModel, true) . ",\n";
$config .= "    'api_key'     => " . var_export($aiKey, true) . ",\n";
$config .= "    'max_tokens'  => 2048,\n";
$config .= "    'temperature' => 0.7,\n";
$config .= "];\n\n";

$config .= "// ─── Framework Data Source ──────────────────────────────────────────────────\n";
$config .= "\$framework_config = [\n";
$config .= "    'source'     => " . var_export($fwSource, true) . ",\n";
$config .= "    'local_path' => " . var_export($fwPath, true) . ",\n";
$config .= "    'remote_url' => '',\n";
$config .= "    'auto_sync'  => false,\n";
$config .= "];\n\n";

$config .= "// ─── App Settings ───────────────────────────────────────────────────────────\n";
$config .= "\$app_config = [\n";
$config .= "    'app_url'                => " . var_export($appUrl, true) . ",\n";
$config .= "    'invite_max_per_coach'   => 20,\n";
$config .= "    'session_timeout_hours'  => 4,\n";
$config .= "    'cohort_cache_hours'     => 1,\n";
$config .= "    'snapshot_enabled'       => true,\n";
$config .= "];\n\n";

$config .= "// ─── QR Code Settings ───────────────────────────────────────────────────────\n";
$config .= "\$qr_config = [\n";
$config .= "    'scale'     => 10,\n";
$config .= "    'logo_path' => null,\n";
$config .= "    'fg_color'  => [46, 117, 182],\n";
$config .= "    'bg_color'  => [255, 255, 255],\n";
$config .= "];\n";

if (file_put_contents($configPath, $config) === false) {
    fwrite(STDERR, "ERROR: Could not write config.php to $configPath\n");
    exit(1);
}

echo "ElevateHER config written to $configPath\n";
