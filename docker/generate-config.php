<?php
/**
 * Generates admin/config/config.php from Docker environment variables.
 * Called by entrypoint.sh on first container start.
 */

$configPath = '/var/www/public_html/admin/config/config.php';
if (file_exists($configPath)) {
    exit(0);
}

$dbHost   = getenv('DB_HOST_MAIN')  ?: 'db';
$dbName   = getenv('DB_NAME_MAIN')  ?: 'elevateher_admin_main';
$dbUser   = getenv('DB_USER')       ?: 'root';
$dbPass   = getenv('DB_PASSWORD')   ?: '';
$hidden   = getenv('HIDDEN_HASH')   ?: bin2hex(random_bytes(32));
$secret   = getenv('APP_SECRET')    ?: bin2hex(random_bytes(32));
$filesLoc = getenv('FILES_LOCATION') ?: '/var/www/files/';

$shard1Host = getenv('DB_HOST_SHARD')  ?: $dbHost;
$shard1Name = getenv('DB_NAME_SHARD')  ?: 'elevateher_admin_shard_1';
$shard2Host = getenv('DB_HOST_SHARD2') ?: $dbHost;
$shard2Name = getenv('DB_NAME_SHARD2') ?: 'elevateher_admin_shard_2';

$smtpHost     = getenv('SMTP_HOST')      ?: 'mailhog';
$smtpPort     = getenv('SMTP_PORT')      ?: 1025;
$smtpUser     = getenv('SMTP_USER')      ?: '';
$smtpPass     = getenv('SMTP_PASS')      ?: '';
$mailFrom     = getenv('MAIL_FROM')      ?: 'noreply@localhost';
$mailFromName = getenv('MAIL_FROM_NAME') ?: 'ElevateHER';

$config = "<?php\n";
$config .= "// Auto-generated by Docker entrypoint on " . date('Y-m-d H:i:s') . "\n\n";
$config .= "\$dbHostSpec  = " . var_export($dbHost, true) . ";\n";
$config .= "\$dbInstance  = " . var_export($dbName, true) . ";\n";
$config .= "\$dbUserName  = " . var_export($dbUser, true) . ";\n";
$config .= "\$dbPassword  = " . var_export($dbPass, true) . ";\n\n";

$config .= "\$shardConfigs = [\n";
$config .= "    'shard1' => [\n";
$config .= "        'host' => " . var_export($shard1Host, true) . ",\n";
$config .= "        'name' => " . var_export($shard1Name, true) . ",\n";
$config .= "        'user' => " . var_export($dbUser, true) . ",\n";
$config .= "        'pass' => " . var_export($dbPass, true) . ",\n";
$config .= "    ],\n";
$config .= "    'shard2' => [\n";
$config .= "        'host' => " . var_export($shard2Host, true) . ",\n";
$config .= "        'name' => " . var_export($shard2Name, true) . ",\n";
$config .= "        'user' => " . var_export($dbUser, true) . ",\n";
$config .= "        'pass' => " . var_export($dbPass, true) . ",\n";
$config .= "    ],\n";
$config .= "];\n\n";

$config .= "\$hiddenhash     = " . var_export($hidden, true) . ";\n";
$config .= "\$app_secret     = " . var_export($secret, true) . ";\n\n";
$config .= "\$files_location = " . var_export($filesLoc, true) . ";\n\n";

$config .= "\$smtp_host      = " . var_export($smtpHost, true) . ";\n";
$config .= "\$smtp_port      = " . var_export((int)$smtpPort, true) . ";\n";
$config .= "\$smtp_user      = " . var_export($smtpUser, true) . ";\n";
$config .= "\$smtp_pass      = " . var_export($smtpPass, true) . ";\n";
$config .= "\$mail_from      = " . var_export($mailFrom, true) . ";\n";
$config .= "\$mail_from_name = " . var_export($mailFromName, true) . ";\n\n";

$config .= "// OAuth (configure later)\n";
$config .= "\$google_client_id     = '';\n";
$config .= "\$google_client_secret = '';\n";
$config .= "\$github_client_id     = '';\n";
$config .= "\$github_client_secret = '';\n";
$config .= "\$facebook_app_id      = '';\n";
$config .= "\$facebook_app_secret  = '';\n\n";
$config .= "\$grecaptcha_key    = '';\n";
$config .= "\$grecaptcha_secret = '';\n\n";
$config .= "\$stripe_secret_key = '';\n";
$config .= "\$stripe_public_key = '';\n\n";
$config .= "\$vapid_subject     = '';\n";
$config .= "\$vapid_public_key  = '';\n";
$config .= "\$vapid_private_key = '';\n";

if (file_put_contents($configPath, $config) === false) {
    fwrite(STDERR, "ERROR: Could not write config.php to $configPath\n");
    exit(1);
}

echo "Config written to $configPath\n";
